const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { compile } = require('./ui-build/node_modules/@vue/compiler-dom');
const { parse, serialize } = require('./ui-build/node_modules/parse5');
const { parse: parseJs } = require('./ui-build/node_modules/@babel/parser');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'web/index.html'), 'utf8');
const findApp = node => node.attrs?.some(attr => attr.name === 'id' && attr.value === 'app')
  ? node : (node.childNodes || []).map(findApp).find(Boolean);
const app = findApp(parse(html));
if (!app) throw new Error('Missing app template');
const context = vm.createContext({ console });
vm.runInContext(fs.readFileSync(path.join(root, 'web/assets/vendor/vue.global.prod.js'), 'utf8'), context);
const compilerVersion = require('./ui-build/node_modules/@vue/compiler-dom/package.json').version;
if (context.Vue.version !== compilerVersion) throw new Error('Vue runtime/compiler version mismatch');
const { code } = compile(serialize(app), { mode: 'function', hoistStatic: true });
let result = `// Generated by scripts/compile-ui.cjs; edit the original HTML/JS templates.\nwindow.RPCompiledMainRender = (function () {\n${code}\n})();\nwindow.RPCompiledRenders = {};\n`;
const classic = compile(fs.readFileSync(path.join(root, 'web/assets/themes/classic/layout.html'), 'utf8'),
  { mode: 'function', hoistStatic: true });
result += `window.RPCompiledClassicRender = (function () {\n${classic.code}\n})();\n`;
const names = new Set();
const visit = node => {
  if (!node || typeof node !== 'object') return;
  if (node.type === 'VariableDeclarator' && node.id.type === 'Identifier' && node.init?.type === 'ObjectExpression') {
    const template = node.init.properties.find(property => property.key?.name === 'template')?.value;
    if (template?.type === 'TemplateLiteral' && !template.expressions.length) {
      const name = node.id.name;
      if (names.has(name)) throw new Error('Duplicate component: ' + name);
      names.add(name);
      const compiled = compile(template.quasis[0].value.cooked, { mode: 'function', hoistStatic: true });
      result += `window.RPCompiledRenders.${name} = (function () {\n${compiled.code}\n})();\n`;
    }
  }
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(visit);
    else if (value && typeof value === 'object') visit(value);
  }
};
for (const file of ['ui-components', 'workspace-ui', 'app-shell', 'gallery-page', 'stream-import-ui', 'app']) {
  visit(parseJs(fs.readFileSync(path.join(root, `web/assets/js/${file}.js`), 'utf8')));
}
result += `
for (const group of [window.RPHubComponents, window.RPHubLayoutComponents, window.RPAppShell, window.RPLocalWorkspace]) {
  for (const [name, component] of Object.entries(group || {})) {
    if (component && typeof component === 'object' && window.RPCompiledRenders[name])
      component.render = window.RPCompiledRenders[name];
  }
}
if (window.RPGalleryPage) window.RPGalleryPage.render = window.RPCompiledRenders.GalleryPage;
if (window.RPStreamImportPanel) window.RPStreamImportPanel.render = window.RPCompiledRenders.StreamImportPanel;
`;
new vm.Script(result);
fs.writeFileSync(path.join(root, 'web/assets/js/main-render.js'), result);
console.log(`Compiled main UI and ${names.size} components with Vue ${compilerVersion}: ${Buffer.byteLength(result)} bytes`);
